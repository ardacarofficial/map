import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { generateToolsJson } from "../src/publishedCatalogue.ts";
import { AGENT_LIMITS } from "../src/contracts.ts";
const catalogue = generateToolsJson();
const hash = createHash("sha256").update(catalogue).digest("hex");
await writeFile(new URL("../schema/tools.json", import.meta.url), catalogue, "utf8");
await writeFile(new URL("../src/catalogue.generated.ts", import.meta.url),
  `// Generated by pnpm --filter @smap/agent gen. Do not edit.\nexport const TOOL_CATALOGUE_HASH = "${hash}";\n`, "utf8");
await writeFile(new URL("../guide/limits.md", import.meta.url), limitsMarkdown(), "utf8");

/** Full limits table served as harita://guide/limits (get_session shows only the essentials). */
function limitsMarkdown(): string {
  const rows = Object.entries(AGENT_LIMITS).map(([key, value]) => `| ${key} | ${value} |`);
  return `# Harita limits\n\nGenerated from AGENT_LIMITS. Cell counts are map cells; *Ms values are milliseconds; *Bytes values are bytes.\n\n| Limit | Value |\n|---|---|\n${rows.join("\n")}\n`;
}
