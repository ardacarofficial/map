import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { argumentSchema } from "../src/i18n/schema.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../src/i18n");
const read = (id: string): Record<string, string> => Object.fromEntries(
  readdirSync(resolve(root, "locales", id)).filter(file => file.endsWith(".json") && file !== "meta.json").sort().flatMap(file =>
    Object.entries(JSON.parse(readFileSync(resolve(root, "locales", id, file), "utf8")) as Record<string, string>).map(([key, value]) => [`${file.slice(0, -5)}.${key}`, value])),
);
const tr = read("tr");
const en = read("en");
const schema = (messages: Record<string, string>, locale: string) => Object.fromEntries(Object.keys(messages).sort().map(key => {
  if (!messages[key]) throw new Error(`Empty message: ${locale}:${key}`);
  return [key, argumentSchema(messages[key]!, locale)];
}));
const argumentsTr = schema(tr, "tr");
const argumentsEn = schema(en, "en");
// Plain arguments may become numeric when a translator needs plural/number syntax.
// The required placeholder names must still be identical.
const names = (args: typeof argumentsTr) => Object.fromEntries(Object.entries(args).map(([key, params]) => [key, Object.keys(params)]));
if (JSON.stringify(names(argumentsTr)) !== JSON.stringify(names(argumentsEn))) throw new Error("TR/EN key or placeholder mismatch");
// Use the strongest type required by either built-in locale.
for (const [key, args] of Object.entries(argumentsEn)) for (const [arg, kind] of Object.entries(args)) if (kind === "number") argumentsTr[key]![arg] = kind;
const digest = createHash("sha256").update(JSON.stringify({ tr, en })).digest("hex");
const output = `// Resource SHA-256: ${digest}\n// Generated by pnpm i18n:gen. Do not edit.\nexport const messageArguments = ${JSON.stringify(argumentsTr, null, 2)} as const;\n\nexport type MessageKey = keyof typeof messageArguments;\nexport type MessageArguments<K extends MessageKey> = {\n  readonly [P in keyof (typeof messageArguments)[K]]: (typeof messageArguments)[K][P] extends "number" ? number | \x60\x24{number}\x60 : string | number;\n};\n`;
const target = resolve(root, "messages.generated.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Stale i18n schema. Run pnpm i18n:gen");
} else writeFileSync(target, output);
