import { expect, it, vi } from 'vitest';
import { createDocument, MapStore } from '@smap/core';
import { useEditorStore } from './editorStore';
import { usePixelUi } from './pixelUi';
import { installPixelViewSettings } from './pixelViewSettings';
const session = vi.hoisted(() => ({ ws: null as unknown, folder: { ref: 'C:/world' }, saved: () => {} }));
vi.mock('../io/session', () => ({ getLevelWorkspace: () => session.ws, getProjectFolder: () => session.folder, onProjectSaved: (cb: () => void) => { session.saved = cb; return () => {}; } }));
it('persists per world/map, restores a replacement store, migrates Save As and clamps half-pixel centers after resize', async () => {
  const data = new Map<string, string>(); vi.stubGlobal('localStorage', { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string, v: string) => data.set(k, v) });
  const a = new MapStore(createDocument({ width: 4, height: 4, tileWidth: 16, tileHeight: 16 }));
  session.ws = { levels: [{ id: 'a' }], activeId: 'a', active: { store: a } };
  const project = { name: 'World', levelId: 'a', levelPath: 'levels/a.json', store: a };
  useEditorStore.setState({ project });
  let off = installPixelViewSettings(); await Promise.resolve(); await Promise.resolve();
  usePixelUi.getState().mirrorOrigins.set(a, { x: 10.5, y: 50.5 });
  usePixelUi.setState(s => ({ mirrorH: true, mirrorV: true, originRevision: s.originRevision + 1 }));
  const b = new MapStore(createDocument({ width: 4, height: 4, tileWidth: 16, tileHeight: 16 }));
  useEditorStore.setState({ project: { ...project, store: b } });
  expect(usePixelUi.getState().mirrorOrigins.get(b)).toEqual({ x: 10.5, y: 50.5 });
  session.folder = { ref: 'C:/copy' }; session.saved(); await Promise.resolve(); await Promise.resolve();
  off(); usePixelUi.setState({ mirrorH: false, mirrorV: false, mirrorOrigins: new WeakMap() });
  session.ws = { levels: [{ id: 'a' }], activeId: 'a', active: { store: b } };
  off = installPixelViewSettings(); await Promise.resolve(); await Promise.resolve();
  expect(usePixelUi.getState().mirrorH).toBe(true); expect(usePixelUi.getState().mirrorV).toBe(true);
  expect(usePixelUi.getState().mirrorOrigins.get(b)).toEqual({ x: 10.5, y: 50.5 });
  b.dispatch({ type: 'resizeMap', width: 1, height: 1 });
  expect(usePixelUi.getState().mirrorOrigins.get(b)).toEqual({ x: 10.5, y: 15 });
  off(); vi.unstubAllGlobals(); useEditorStore.setState({ project: null });
});
